class AssessmentGenerateView(APIView):
    permission_classes = [
        IsAuthenticated,
    ]

    def post(self, request, id):
        analysis = (
            _analysis_queryset_for_user(
                request.user
            )
            .filter(id=id)
            .first()
        )

        if analysis is None:
            return Response(
                {
                    "detail": (
                        "Risk analysis not found."
                    )
                },
                status=(
                    status.HTTP_404_NOT_FOUND
                ),
            )

        if (
            analysis.status
            != RiskAnalysis.STATUS_READY
            or not analysis.processed
        ):
            return Response(
                {
                    "detail": (
                        "The risk analysis is not "
                        "ready."
                    )
                },
                status=(
                    status.HTTP_409_CONFLICT
                ),
            )

        result = llm.generate_assessment(
            analysis.processed
        )

        assessment_text = result[
            "assessment"
        ]
        cited_evidence = (
            llm.select_cited_evidence(
                assessment_text,
                analysis.processed.get(
                    "evidence",
                    [],
                ),
            )
        )

        record = (
            AssessmentResult.objects.create(
                analysis=analysis,
                assessment_text=(
                    assessment_text
                ),
                recommendations=(
                    result[
                        "recommendations"
                    ]
                ),
                avoid=result["avoid"],
                evidence=(
                    cited_evidence
                ),
                model_used=(
                    result["model_used"]
                ),
                is_fallback=(
                    result["is_fallback"]
                ),
            )
        )

        return Response(
            AssessmentResultSerializer(
                record
            ).data,
            status=status.HTTP_201_CREATED,
        )


class AssessmentLatestView(
    generics.RetrieveAPIView
):
    serializer_class = (
        AssessmentResultSerializer
    )
    permission_classes = [
        IsAuthenticated,
    ]

    def get_object(self):
        analysis_id = self.kwargs["id"]

        allowed_analysis = (
            _analysis_queryset_for_user(
                self.request.user
            )
            .filter(id=analysis_id)
            .values_list(
                "id",
                flat=True,
            )
            .first()
        )

        if allowed_analysis is None:
            raise Http404(
                "Risk analysis not found."
            )

        assessment = (
            AssessmentResult.objects
            .filter(
                analysis_id=analysis_id
            )
            .order_by("-created_at")
            .first()
        )

        if assessment is None:
            raise Http404(
                "No assessment has been "
                "generated yet."
            )

        return assessment
